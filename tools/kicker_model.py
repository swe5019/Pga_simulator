#!/usr/bin/env python3
"""
kicker_model.py — DraftKings showdown scoring for kickers, from the market.

WHY THIS EXISTS
Kickers do not appear in a DraftKings classic lineup, so the project ignored
them, and every showdown build it produced simply left the slot empty. That
was not a small omission. On 19 November Ka'imi Fairbairn was 35.1% owned and
appeared in 100% OF THE TOP 1% of entries, with the other kicker, Spencer
Shrader, in 80.2% of it. The 9 November winner carried two kickers. Three
lineups this project recommended on 19 November all lost, and none of them
could even see the slot.

NO HISTORY EXISTS TO FIT. data/nfl_2026.json holds 575 players and not one
kicker: the stats pipeline has never ingested them. So this is built the same
way the rest of the projections are, by de-vigging the player's own markets,
which needs no history at all.

THE MARKETS
Books post three kicker lines, and this project's snapshots carry all of them:

    FG Made           how many field goals
    XP Made           how many extra points
    Kicking Points    3 per field goal plus 1 per extra point

Each is de-vigged across its two sides and inverted against a Poisson to
recover an expected count. Poisson is the right family here: a kicker's
attempts are rare independent events generated by drives, which is exactly
what it describes, and the whole quantity is small enough that the choice of
family matters far less than the line does.

DRAFTKINGS IS NOT KICKING POINTS
The book's Kicking Points market scores a field goal at 3 whatever its length.
DraftKings pays a bonus for distance:

    0 to 39 yards   3 points
    40 to 49        4
    50 or more      5
    extra point     1

So DK points exceed the Kicking Points line by a bonus that depends on how far
the kicks are, which no market on the board prices.

THE ANCHOR IS "KICKING POINTS", NOT THE TWO COMPONENTS. All three markets
agree closely once de-vigged, the components giving 7.60 against the combined
market's 7.40 over the captured contests, but Kicking Points is a single line
on exactly the quantity wanted and so needs the least extrapolation. FG Made
and XP Made are used to split it, which only matters for the distance bonus
and for the shape of the sampled distribution.

WHAT CAN AND CANNOT BE CLAIMED HERE

Across the nine kickers in the captured showdowns whose lines are recoverable
from the props archive, this is UNBIASED: mean projection 7.67 against mean
actual 7.67. That is the one property nine observations can establish.

SKILL IS UNPROVEN AND THE TEST HAS NO POWER TO PROVE IT. Actual DK scores had
a standard deviation of 2.55 while the market's predictions spread only 1.10,
implying about 2.30 of irreducible noise. So a PERFECT model would still
average 1.83 points of error and a flat league average would average 2.03.
The entire detectable gap is 0.20 points, and the standard error on nine
observations is 0.85. Nine kickers cannot resolve a fifth of a point. Anyone
reporting that this model beats or loses to a flat average on this sample is
reporting noise, and that includes the first version of this file.

Ship it anyway, for a reason that does not depend on the comparison: the
alternative in this project was NO KICKER AT ALL, and a slot worth about 7.7
points was being scored as zero. On 19 November that slot was in 100% of the
top 1% of entries.

BONUS_PER_FG is the one free parameter and it is set to keep the projection
unbiased on the nine. It comes out small, near 0.15 a kick, where a league
average distance mix of 55/30/15 would imply 0.60. Those disagree and the
data cannot say which is right, so the small value is used because it is the
measured one and because being unbiased is worth more than being theoretically
tidy. Revisit at thirty observations.

WHAT THIS DOES NOT DO
It does not model blocked kicks, weather, a kicker being benched mid-game, or
the correlation between a kicker and his own offence, which is real and
negative in the red zone: a touchdown costs him three points and pays him one.
That correlation belongs in the joint simulation, not here, and is noted as
the obvious next step.

A KICKER WITH NO MARKETS IS PROBABLY NOT PLAYING. On 16 November both of that
slate's kickers carried no lines and both went unrostered by the field. The
same guard the ownership models use applies: see flex_ownership.is_rostered.
"""
import math

# DraftKings showdown kicker scoring.
FG_BASE = 3.0
XP_VALUE = 1.0

# Expected DraftKings bonus per field goal made, above the book's flat 3.
# Set so the projection is unbiased over the nine captured kickers. See the
# docstring: a league average distance mix would imply about 0.60 instead, and
# the data cannot adjudicate. Revisit at thirty observations.
BONUS_PER_FG = 0.15

# Share of made field goals by distance, used only to SAMPLE a score once the
# expected count is known. The mean it produces is overridden by
# BONUS_PER_FG, so these affect the shape of the distribution and not its
# centre.
DIST_MIX = ((0.55, 3.0), (0.30, 4.0), (0.15, 5.0))

# Fallbacks when a market is missing but the kicker is clearly playing.
# FG_PER_GAME matches the constant build_projections.py already uses for
# points allowed, so the two models cannot quietly disagree.
FG_PER_GAME = 1.7
XP_PER_GAME = 2.2


def _fair(over_decimal, under_decimal):
    """De-vig two decimal prices into a probability for the OVER."""
    if not over_decimal or not under_decimal:
        return None
    a, b = 1.0 / over_decimal, 1.0 / under_decimal
    tot = a + b
    return (a / tot) if tot > 0 else None


def _poisson_tail(lam, k):
    """P(X >= k) for X ~ Poisson(lam)."""
    if lam <= 0:
        return 0.0 if k > 0 else 1.0
    # 1 - sum_{i<k} e^-lam lam^i / i!
    acc, term = 0.0, math.exp(-lam)
    for i in range(k):
        acc += term
        term *= lam / (i + 1)
    return max(0.0, min(1.0, 1.0 - acc))


def lam_from_line(p_over, line):
    """Recover a Poisson mean from "P(count > line)".

    A line of 1.5 means the over needs 2 or more, so this solves
    P(X >= ceil(line)) = p_over by bisection, which is stable because the tail
    is monotone in lam.
    """
    if p_over is None or line is None:
        return None
    k = int(math.floor(line)) + 1
    if not 0.0 < p_over < 1.0:
        return None
    lo, hi = 1e-6, 30.0
    for _ in range(80):
        mid = (lo + hi) / 2.0
        if _poisson_tail(mid, k) < p_over:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2.0


def expectations(markets):
    """markets: {stat: {'over': {'line','decimal'}, 'under': {...}}}
    -> (lam_fg, lam_xp, source), where source names what it actually used.

    Prefers the two component markets. Falls back to Kicking Points, which
    constrains 3*fg + xp but not the split, resolved with the league ratio.
    """
    def lam(stat):
        m = markets.get(stat) or {}
        o, u = m.get("over") or {}, m.get("under") or {}
        p = _fair(o.get("decimal"), u.get("decimal"))
        if p is None and o.get("line") is not None:
            # One-sided price: treat the line as the median, which for a
            # count means the mean sits near it.
            return float(o["line"]), "line only"
        return lam_from_line(p, o.get("line")), "de-vigged"

    fg, _fs = lam("FG Made")
    xp, _xs = lam("XP Made")
    kp, _ks = lam("Kicking Points")

    # Kicking Points is the anchor: one line on exactly the quantity wanted.
    # The components only set the split, so a bad component cannot move the
    # total, which is the number that matters.
    if kp is not None:
        if fg is not None and xp is not None and (FG_BASE * fg + xp) > 0:
            share = FG_BASE * fg / (FG_BASE * fg + xp)
        else:
            share = ((FG_BASE * FG_PER_GAME)
                     / (FG_BASE * FG_PER_GAME + XP_PER_GAME))
        return (kp * share / FG_BASE), (kp * (1.0 - share)), "kicking points"

    if fg is not None and xp is not None:
        return fg, xp, "FG and XP markets, no combined line"
    if fg is not None:
        return fg, XP_PER_GAME, "FG market, XP from the league rate"
    if xp is not None:
        return FG_PER_GAME, xp, "XP market, FG from the league rate"
    return None, None, "no market"


def projected_points(markets):
    """Expected DraftKings showdown points. None when nothing is priced."""
    fg, xp, src = expectations(markets)
    if fg is None:
        return None, src
    return (FG_BASE + BONUS_PER_FG) * fg + XP_VALUE * xp, src


def sample_points(rng, markets, trials):
    """A simulated DK score per trial, for the showdown solver.

    Returns None when the kicker is unpriced, so a caller can leave him out
    rather than invent a distribution for him.
    """
    fg, xp, _src = expectations(markets)
    if fg is None:
        return None
    n_fg = rng.poisson(fg, trials)
    n_xp = rng.poisson(xp, trials)
    out = n_xp * XP_VALUE
    probs = [p for p, _v in DIST_MIX]
    vals = [v for _p, v in DIST_MIX]
    biggest = int(max(n_fg.max(), 1))
    for i in range(biggest):
        hit = n_fg > i
        if not hit.any():
            break
        draw = rng.choice(vals, size=int(hit.sum()), p=probs)
        out = out.astype(float)
        out[hit] += draw
    # Re-centre on the documented expectation: DIST_MIX fixes the shape, and
    # BONUS_PER_FG fixes the mean, so the two must not disagree.
    target = (FG_BASE + BONUS_PER_FG) * fg + XP_VALUE * xp
    cur = out.mean()
    if cur > 0:
        out = out * (target / cur)
    return out


def describe():
    return (f"kicker scoring anchored on the book's kicking points market, "
            f"de-vigged and inverted against a Poisson, plus {BONUS_PER_FG} of "
            f"DraftKings distance bonus per field goal. Unbiased over the nine "
            f"kickers on file; skill is unproven and nine observations have no "
            f"power to prove it. No kicker history exists to fit")
